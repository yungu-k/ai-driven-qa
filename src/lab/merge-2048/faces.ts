/** 격자 → <rect>. 같은 색이 가로로 이어지면 한 칸으로 묶는다 */
export function gridToRects(rows: string[]): string {
  let out = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let w = 1;
      while (row[x + w] === ch) w++;
      const fill = PAL[ch];
      if (fill) out += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${fill}"/>`;
      x += w;
    }
  });
  return out;
}

export function faceFor(v: number): string {
  const rows = FACES[v] ?? FACES[2048];
  return `<svg viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${gridToRects(rows)}</svg>`;
}
